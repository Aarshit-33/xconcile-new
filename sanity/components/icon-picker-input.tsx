export const TrustIconPickerInput = makeIconPicker(trustIconSet);

/** Icon as Studio preview media (array item thumbnail). */
export function iconMedia(name: unknown, iconSet: IconSet = siteIconSet): PreviewValue["media"] {
  if (typeof name !== "string") return undefined;
  const Icon = iconSet.icons[name];
  return Icon ? createElement(Icon, { width: 24, height: 24 }) : undefined;
}

/**
 * Preview for an object with an `icon` field: the given title/subtitle paths, the icon as media.
 * `iconPreview({ title: "title", subtitle: "body" })`.
 */
export function iconPreview(
  select: { title: string; subtitle?: string },
  iconSet: IconSet = siteIconSet,
) {
  return {
    select: { title: select.title, subtitle: select.subtitle ?? select.title, icon: "icon" },
    prepare: ({ title, subtitle, icon }: { title?: string; subtitle?: string; icon?: string }) => ({
      title,
      subtitle: select.subtitle ? subtitle : undefined,
      media: iconMedia(icon, iconSet),
    }),
  };
}

