/**
 * Studio icon pickers (user request 2026-10-26): every icon field shows a searchable grid of the
 * site's own icons instead of a name dropdown, and array items show their icon as the thumbnail.
 * The stored value is unchanged (the icon name string, e.g. "trending_down"), so existing content
 * and the website are not affected.
 *
 * 2026-10-27 ("much more icons", option A): the site set is ~290 Material Symbols generated by
 * scripts/generate-site-icons.mjs, grouped in categories (filter chips). The header menu and the
 * Home contact trust signals offer the same set after their own legacy icons.
 *
 * Plain elements + Sanity UI CSS variables (no direct @sanity/ui dependency in package.json).
 * Only the Studio loads this (sanity.config.ts → app/studio Studio.tsx, a client component).
 */

type SvgIcon = ComponentType<{ width?: number; height?: number }>;
export type IconCategory = { id: string; title: string; icons: readonly string[] };
/** Name → icon component, optional readable labels (default: the name with spaces) and categories. */
export type IconSet = {
  icons: Record<string, SvgIcon>;
  labels?: Record<string, string>;
  categories?: readonly IconCategory[];
};

const siteIcons = iconRegistry as Record<string, SvgIcon>;

/** Section icons (components/icons/registry.tsx): Intro, Services, Challenges, Process, … */
export const siteIconSet: IconSet = { icons: siteIcons, categories: siteIconCategories };

/**
 * A field's own icons first (category `first`), then every site icon whose name they don't
 * already use. The website renders a legacy name with the legacy icon, anything else as a site icon.
 */
function withSiteIcons(
  first: IconCategory,
  icons: Record<string, SvgIcon>,
  labels?: Record<string, string>,
): IconSet {
  const taken = new Set(Object.keys(icons));
  return {
    icons: { ...siteIcons, ...icons },
    labels,
    categories: [
      first,
      ...siteIconCategories
        .map((c) => ({ ...c, icons: c.icons.filter((n) => !taken.has(n)) }))
        .filter((c) => c.icons.length),
    ],
  };
}

/** Header mega-menu (Site Settings → Header → Menus): old-site outline icons + the site set. */
export const navIconSet: IconSet = withSiteIcons(
  { id: "menu", title: "Menu outline icons", icons: NAV_ICON_NAMES },
  Object.fromEntries(
    NAV_ICON_NAMES.map((name) => {
      const Icon: SvgIcon = ({ width = 24, height = 24 }) =>
        createElement(
          "span",
          { style: { display: "inline-flex", width, height } },
          createElement(NavIcon, { name }),
        );
      Icon.displayName = `NavIcon(${name})`;
      return [name, Icon];
    }),
  ),
);

