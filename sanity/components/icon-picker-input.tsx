const labelOf = (iconSet: IconSet, name: string) =>
  iconSet.labels?.[name] ?? name.replace(/[_-]/g, " ");

/** `options.list` for a string field using a set (Sanity validates the stored value against it). */
export const iconListOptions = (iconSet: IconSet) =>
  Object.keys(iconSet.icons)
    .sort()
    .map((value) => ({ title: labelOf(iconSet, value), value }));

/**
 * Input component for one icon set: current choice (preview tile + name), then a collapsible panel
 * with search, category chips and the icon grid. The panel starts open when nothing is chosen.
 * `clearable`: optional fields get a "Remove icon" button (required fields always keep one).
 */
export function makeIconPicker(
  iconSet: IconSet,
  { clearable = false }: { clearable?: boolean } = {},
) {
  const all = Object.keys(iconSet.icons).sort((a, b) =>
    labelOf(iconSet, a).localeCompare(labelOf(iconSet, b)),
  );
  const categories = iconSet.categories ?? [];
  /** Name → category titles, so "tax" or "security" also finds the icons of that category. */
  const categoryText: Record<string, string> = {};
  for (const c of categories)
    for (const n of c.icons) categoryText[n] = `${categoryText[n] ?? ""} ${c.title.toLowerCase()}`;

  function IconPicker(props: StringInputProps) {
    const { value, onChange, readOnly, elementProps } = props;
    const { id, ref, onFocus, onBlur } = elementProps;
    const [open, setOpen] = useState(!value);
    const [query, setQuery] = useState("");
    const [category, setCategory] = useState("all");
    const searchId = useId();

    const shown = useMemo(() => {
      const pool =
        category === "all" ? all : (categories.find((c) => c.id === category)?.icons ?? all);
      const q = query.trim().toLowerCase();
      if (!q) return pool;
      const words = q.split(/\s+/);
      return pool.filter((n) => {
        const text = `${n.toLowerCase()} ${labelOf(iconSet, n).toLowerCase()}${categoryText[n] ?? ""}`;
        return words.every((w) => text.includes(w));
      });
    }, [query, category]);

    const Selected = value ? iconSet.icons[value] : undefined;
    const choose = (name: string) => {
      onChange(set(name));
      setOpen(false);
    };

    return (
      <div style={{ display: "grid", gap: 12 }}>
        {/* Current choice (the preview) */}
        <div style={{ display: "flex", alignItems: "center", gap: 12, flexWrap: "wrap" }}>
          <button
            type="button"
            disabled={readOnly}
            aria-label={open ? "Close icon picker" : "Choose icon"}
            onClick={() => setOpen((o) => !o)}
            style={{
              ...tile,
              width: 56,
              height: 56,
              background: "var(--card-bg-color, #fff)",
              color: "var(--card-fg-color, inherit)",
              cursor: readOnly ? "default" : "pointer",
              ...(Selected ? selectedTile : {}),
            }}
          >
            {Selected ? (
              createElement(Selected, { width: 32, height: 32 })
            ) : (
              <span style={muted}>—</span>
            )}
          </button>
          <span style={{ display: "grid", gap: 2, minWidth: 0 }}>
            <span style={{ fontSize: 14, fontWeight: 600, textTransform: "capitalize" }}>
              {value ? labelOf(iconSet, value) : <span style={muted}>No icon selected</span>}
            </span>
            {value ? (
              <code style={{ ...muted, fontSize: 12 }}>
                {value}
                {!Selected ? " (unknown icon, pick another)" : ""}
              </code>
            ) : null}
          </span>
          <span style={{ display: "flex", gap: 8, marginLeft: "auto" }}>
            {!readOnly ? (
              <button
                type="button"
                id={open ? undefined : id}
                ref={open ? undefined : (ref as never)}
                onFocus={open ? undefined : (onFocus as never)}
                onBlur={open ? undefined : (onBlur as never)}
                aria-expanded={open}
                onClick={() => setOpen((o) => !o)}
                style={button}
              >
                {open ? "Close" : value ? "Change icon" : "Choose icon"}
              </button>
            ) : null}
            {clearable && value && !readOnly ? (
              <button type="button" onClick={() => onChange(unset())} style={button}>
                Remove icon
              </button>
            ) : null}
          </span>
        </div>

        {open && !readOnly ? (
          <div style={panel}>
            {/* id/ref/focus handlers: Studio validation messages focus this input. */}
            <input
              id={id ?? searchId}
              ref={ref as never}
              onFocus={onFocus as never}
              onBlur={onBlur as never}
              type="search"
              value={query}
              onChange={(e) => setQuery(e.currentTarget.value)}
              placeholder={`Search ${all.length} icons (e.g. tax, money, team, lock)…`}
              style={search}
            />

            {categories.length ? (
              <div role="tablist" aria-label="Icon categories" style={chips}>
                {[{ id: "all", title: "All", icons: all }, ...categories].map((c) => (
                  <button
                    key={c.id}
                    type="button"
                    role="tab"
                    aria-selected={category === c.id}
                    onClick={() => setCategory(c.id)}
                    style={{ ...chip, ...(category === c.id ? chipActive : {}) }}
                  >
                    {c.title} <span style={{ opacity: 0.7 }}>{c.icons.length}</span>
                  </button>
                ))}
              </div>
            ) : null}

            <div role="listbox" aria-label="Icons" style={grid}>
              {shown.map((name) => {
                const Icon = iconSet.icons[name];
                const active = name === value;
                return (
                  <button
                    key={name}
                    type="button"
                    role="option"
                    aria-selected={active}
                    title={name}
                    onClick={() => choose(name)}
                    style={{ ...option, ...(active ? selectedTile : {}) }}
                  >
                    {createElement(Icon, { width: 24, height: 24 })}
                    <span style={optionLabel}>{labelOf(iconSet, name)}</span>
                  </button>
                );
              })}
              {shown.length === 0 ? (
                <p style={{ ...muted, gridColumn: "1 / -1" }}>
                  No icon matches “{query}”{category !== "all" ? " in this category" : ""}.
                </p>
              ) : null}
            </div>
          </div>
        ) : null}
      </div>
    );
  }
  IconPicker.displayName = "IconPicker";
  return IconPicker;
}

export const IconPickerInput = makeIconPicker(siteIconSet);
/** Site icons for optional fields (e.g. Hiring Models card glyph, case-study impact card). */
export const OptionalIconPickerInput = makeIconPicker(siteIconSet, { clearable: true });
